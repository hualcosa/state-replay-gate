// Copies the shared schema and fixture into web/ and regenerates the TS types.
// Outputs are committed; `pnpm run sync && git status --porcelain web` must stay clean.
import { copyFileSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compileFromFile } from "json-schema-to-typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const schemaSrc = resolve(root, "../schemas/run-artifact.schema.json");
const fixtureSrc = resolve(root, "../schemas/fixtures/run.fixture.json");
const schemaDst = resolve(root, "src/generated/run-artifact.schema.json");
const typesDst = resolve(root, "src/generated/run-artifact.ts");
const fixtureDst = resolve(root, "public/fixtures/run.fixture.json");

mkdirSync(dirname(schemaDst), { recursive: true });
mkdirSync(dirname(fixtureDst), { recursive: true });
copyFileSync(schemaSrc, schemaDst);
copyFileSync(fixtureSrc, fixtureDst);

const ts = await compileFromFile(schemaSrc, {
  bannerComment:
    "/* eslint-disable */\n/**\n * GENERATED by scripts/sync.mjs from ../schemas/run-artifact.schema.json.\n * Do not edit by hand; run `pnpm run sync`.\n */",
  additionalProperties: false,
  cwd: dirname(schemaSrc),
  unreachableDefinitions: true,
  format: true,
});
writeFileSync(typesDst, ts);
console.log("synced schema, fixture and types");
